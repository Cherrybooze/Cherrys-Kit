"""Export supplied RWA resource art without redrawing or recolouring it.
Requires Pillow. Originals and references remain byte-for-byte intact in design/.
"""
from pathlib import Path
import hashlib,json,struct
from PIL import Image,ImageDraw
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'design/rwa-resource-assets-v1'
DEST=ROOT/'Interface/AddOns/CherrysKit/RomWeakAuras/Media/Textures/Resources'
DEST.mkdir(parents=True,exist_ok=True)
SPECS=[
 ('diamond','soul-diamond',(64,64)),
 ('maxLabel','max-label',(256,128)),
 ('metalFrame','bar-frame-metal',(512,64)),
 ('bevelFill','bar-fill-bevel',(256,32)),
 ('glassFill','bar-fill-glass',(256,32)),
]
manifest=json.loads((SOURCE/'asset_manifest.json').read_text())
originals={entry['path']:entry['sha256'] for entry in manifest['files']}
results={}
for key,name,size in SPECS:
 path=SOURCE/'masters'/f'{name}.png'
 assert hashlib.sha256(path.read_bytes()).hexdigest()==originals[f'masters/{name}.png']
 image=Image.open(path).convert('RGBA')
 alpha=image.getchannel('A')
 visible=alpha.point(lambda value:255 if value>8 else 0).getbbox()
 assert visible
 crop=(max(0,visible[0]-8),max(0,visible[1]-8),min(image.width,visible[2]+8),min(image.height,visible[3]+8))
 trimmed=image.crop(crop)
 scale=min((size[0]-4)/trimmed.width,(size[1]-4)/trimmed.height)
 target=(max(1,round(trimmed.width*scale)),max(1,round(trimmed.height*scale)))
 # Premultiplied alpha prevents dark fringes while preserving the approved colours.
 resized=trimmed.convert('RGBa').resize(target,Image.Resampling.LANCZOS).convert('RGBA')
 offset=((size[0]-target[0])//2,(size[1]-target[1])//2)
 canvas=Image.new('RGBA',size,(0,0,0,0));canvas.paste(resized,offset)
 output=DEST/f'{name}.tga'
 canvas.save(output,compression=None)
 header=output.read_bytes()[:18]
 assert header[2]==2 and header[16]==32, 'expected uncompressed32-bit TGA'
 assert struct.unpack('<HH',header[12:16])==size
 box=canvas.getchannel('A').point(lambda value:255 if value>8 else 0).getbbox()
 def bounds(box):return dict(x=box[0]/size[0],y=box[1]/size[1],w=(box[2]-box[0])/size[0],h=(box[3]-box[1])/size[1])
 entry=dict(path='Resources/'+name,width=size[0],height=size[1],content=bounds(box),
   source_sha256=hashlib.sha256(path.read_bytes()).hexdigest(),source_content=list(visible),source_crop=list(crop),
   export_content=list(box),alpha_trim_threshold=8,source_padding=8,canvas_padding=2)
 if key=='metalFrame':
  # Safe clear rectangle inside the actual alpha hole, inspected at source scale.
  opening=(174,324,1998,396)
  assert alpha.crop(opening).getextrema()[1]<=8
  sx,sy=target[0]/trimmed.width,target[1]/trimmed.height
  mapped=(offset[0]+(opening[0]-crop[0])*sx,offset[1]+(opening[1]-crop[1])*sy,
          offset[0]+(opening[2]-crop[0])*sx,offset[1]+(opening[3]-crop[1])*sy)
  entry['opening']=bounds(mapped);entry['source_opening']=list(opening)
 entry['sha256']=hashlib.sha256(output.read_bytes()).hexdigest()
 results[key]=entry
(SOURCE/'runtime_exports.json').write_text(json.dumps(results,indent=2)+'\n')
lines=['-- Supplied resource art; generated by tools/build_rwa_resource_assets.py.',
       '-- Bounds are normalized to the padded TGA canvas, not the visible artwork.',
       'RWA.MEDIA.resources = {']
for key,entry in results.items():
 def lua_bounds(values):return '{'+','.join(k+'='+format(v,'.9g') for k,v in values.items())+'}'
 line='  '+key+'={path="'+entry['path']+'",width='+str(entry['width'])+',height='+str(entry['height'])+',content='+lua_bounds(entry['content'])
 if 'opening' in entry:line+=',opening='+lua_bounds(entry['opening'])
 lines.append(line+'},')
lines.append('}')
lines.append('table.insert(RWA.MEDIA.textureCategories,"Resources")')
lines.append('RWA.MEDIA.textures.Resources={"Resources/soul-diamond","Resources/max-label","Resources/bar-frame-metal","Resources/bar-fill-bevel","Resources/bar-fill-glass"}')
media=ROOT/'Interface/AddOns/CherrysKit/RomWeakAuras/MediaList.lua'
text=media.read_text(encoding='utf-8-sig')
marker='-- Supplied resource art; generated by tools/build_rwa_resource_assets.py.'
if marker in text:text=text[:text.index(marker)]
media.write_text(text.rstrip()+'\n\n'+'\n'.join(lines)+'\n',encoding='utf8')
# Native-sized inspection sheet on a dark HUD background; no runtime composites.
sheet=Image.new('RGBA',(850,240),(7,18,28,255))
draw=ImageDraw.Draw(sheet)
x=20
for key,name,size in SPECS:
 icon=Image.open(DEST/f'{name}.tga').convert('RGBA')
 draw.text((x,12),name,fill='white')
 if key=='diamond':shown=icon.resize((32,32),Image.Resampling.LANCZOS)
 elif key=='maxLabel':shown=icon.resize((80,40),Image.Resampling.LANCZOS)
 elif key=='metalFrame':shown=icon.resize((256,32),Image.Resampling.LANCZOS)
 else:shown=icon.resize((128,16),Image.Resampling.LANCZOS)
 sheet.alpha_composite(shown,(x,48))
 x+=shown.width+25
sheet.convert('RGB').save(ROOT/'dist/resource-assets-inspection.png')
print(json.dumps({key:{k:v for k,v in entry.items() if k in ('path','width','height','content','opening')} for key,entry in results.items()},indent=2))

