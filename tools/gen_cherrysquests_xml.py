"""Writes Interface/AddOns/CherrysKit/CherrysQuests/CherrysQuests.xml.

RoM only runs script handlers declared in XML, so every frame Cherry's Quests draws or clicks
(the tracker, its quest rows and the options rows) is declared here. Run after changing the
frame list: python3 tools/gen_cherrysquests_xml.py
"""

from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "Interface/AddOns/CherrysKit/CherrysQuests/CherrysQuests.xml"
ROWS = 30
OPT_ROWS = 20
TEX = r"Interface\Common\Bar\Smooth"


def anchor(point="TOPLEFT", rel="$parent", relpoint=None, x=0, y=0):
    relpoint = relpoint or point
    return (f'<Anchors><Anchor point="{point}" relativeTo="{rel}" relativePoint="{relpoint}">'
            f'<Offset><AbsDimension x="{x}" y="{y}" /></Offset></Anchor></Anchors>')


def size(w, h):
    return f'<Size><AbsDimension x="{w}" y="{h}" /></Size>'


def texture(name, w=8, h=8, hidden=True):
    hid = ' hidden="true"' if hidden else ""
    return f'<Texture name="{name}" file="{TEX}"{hid}>{size(w, h)}{anchor()}</Texture>'


def font(name, height, justify="LEFT", w=None, h=None, hidden=False, inherits="GameFontHighlight"):
    hid = ' hidden="true"' if hidden else ""
    sz = size(w, h) if w else ""
    return (f'<FontString name="{name}" inherits="{inherits}" justifyH="{justify}" justifyV="TOP" text=""{hid}>'
            f'{sz}<FontHeight><AbsValue val="{height}" /></FontHeight>{anchor()}</FontString>')


def button(name, text, w, h, x, y, onclick):
    return (f'<Button name="{name}" inherits="UIPanelButtonTemplate" text="{text}">{size(w, h)}{anchor(x=x, y=y)}'
            f'<Scripts><OnClick>{onclick}</OnClick></Scripts></Button>')


def quest_row(i):
    n = f"CQ_Row{i}"
    return f"""			<Frame name="{n}" enableMouse="true" hidden="true" id="{i}">
				{size(200, 20)}
				{anchor()}
				<Layers>
					<Layer level="BACKGROUND">
						{texture(n + "Hover")}
					</Layer>
					<Layer level="ARTWORK">
						{texture(n + "Stripe")}
						{texture(n + "BarBg")}
					</Layer>
					<Layer level="OVERLAY">
						{texture(n + "Bar")}
						{font(n + "Title", 13)}
						{font(n + "Text", 11)}
						{font(n + "Npc", 11)}
					</Layer>
				</Layers>
				<Scripts>
					<OnEnter>CherrysQuests.Tracker.RowEnter(this, {i});</OnEnter>
					<OnLeave>CherrysQuests.Tracker.RowLeave(this, {i});</OnLeave>
					<OnMouseUp>CherrysQuests.Tracker.RowClick({i}, key);</OnMouseUp>
				</Scripts>
			</Frame>"""


def opt_row(i):
    n = f"CQ_OptRow{i}"
    y = 44 + (i - 1) * 24
    return f"""			<Frame name="{n}" enableMouse="true" hidden="true">
				{size(430, 24)}
				{anchor(x=12, y=y)}
				<Layers>
					<Layer level="ARTWORK">
						<FontString name="{n}Label" inherits="GameFontHighlight" justifyH="LEFT" text="">{size(230, 20)}<FontHeight><AbsValue val="12" /></FontHeight>{anchor("LEFT", "$parent", "LEFT", 30, 0)}</FontString>
						<FontString name="{n}Value" inherits="GameFontHighlight" justifyH="CENTER" text="" hidden="true">{size(70, 20)}<FontHeight><AbsValue val="12" /></FontHeight>{anchor("LEFT", "$parent", "LEFT", 288, 0)}</FontString>
					</Layer>
				</Layers>
				<Frames>
					<CheckButton name="{n}Check" inherits="UIPanelCheckButtonTemplate" hidden="true">{size(24, 24)}{anchor("LEFT", "$parent", "LEFT", 2, 0)}
						<Scripts><OnClick>CherrysQuests.Options.Click({i}, "check");</OnClick></Scripts>
					</CheckButton>
					<Button name="{n}Minus" inherits="UIPanelButtonTemplate" text="-" hidden="true">{size(26, 22)}{anchor("LEFT", "$parent", "LEFT", 260, 0)}
						<Scripts><OnClick>CherrysQuests.Options.Click({i}, "minus");</OnClick></Scripts>
					</Button>
					<Button name="{n}Plus" inherits="UIPanelButtonTemplate" text="+" hidden="true">{size(26, 22)}{anchor("LEFT", "$parent", "LEFT", 360, 0)}
						<Scripts><OnClick>CherrysQuests.Options.Click({i}, "plus");</OnClick></Scripts>
					</Button>
					<Button name="{n}Choice" inherits="UIPanelButtonTemplate" text="" hidden="true">{size(166, 22)}{anchor("LEFT", "$parent", "LEFT", 260, 0)}
						<Scripts><OnClick>CherrysQuests.Options.Click({i}, "choice");</OnClick></Scripts>
					</Button>
				</Frames>
				<Scripts>
					<OnEnter>CherrysQuests.Options.Enter({i}, this);</OnEnter>
					<OnLeave>GameTooltip:Hide();</OnLeave>
				</Scripts>
			</Frame>"""


def build():
    rows = "\n".join(quest_row(i) for i in range(1, ROWS + 1))
    opts = "\n".join(opt_row(i) for i in range(1, OPT_ROWS + 1))
    opt_h = 44 + OPT_ROWS * 24 + 82
    return f"""<Ui xmlns="http://www.runewaker.com/" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:schemaLocation="http://www.runewaker.com/UI.xsd">
	<!-- Generated by tools/gen_cherrysquests_xml.py. -->
	<Frame name="CQ_Events" parent="UIParent">
		{size(1, 1)}
		{anchor(rel="UIParent")}
		<Scripts>
			<OnLoad>CherrysQuests.OnLoad(this);</OnLoad>
			<OnEvent>CherrysQuests.OnEvent(event, arg1, arg2);</OnEvent>
			<OnUpdate>CherrysQuests.OnUpdate(elapsedTime);</OnUpdate>
		</Scripts>
	</Frame>
	<Frame name="CQ_Tracker" parent="UIParent" frameStrata="LOW" movable="true" hidden="true">
		{size(230, 40)}
		{anchor(rel="UIParent", x=700, y=220)}
		<Layers>
			<Layer level="BACKGROUND">
				{texture("CQ_TrackerBg", 230, 40, hidden=False)}
			</Layer>
		</Layers>
		<Frames>
			<Frame name="CQ_Head" enableMouse="true">
				{size(230, 22)}
				{anchor()}
				<Layers>
					<Layer level="BACKGROUND">
						{texture("CQ_HeadBg", 230, 22, hidden=False)}
					</Layer>
					<Layer level="ARTWORK">
						{texture("CQ_HeadAccent", 230, 2, hidden=False)}
					</Layer>
					<Layer level="OVERLAY">
						{font("CQ_HeadTitle", 13)}
					</Layer>
				</Layers>
				<Scripts>
					<OnMouseDown>CherrysQuests.Tracker.HeadDown(key);</OnMouseDown>
					<OnMouseUp>CherrysQuests.Tracker.HeadUp(key);</OnMouseUp>
					<OnEnter>CherrysQuests.Tracker.HeadEnter(this);</OnEnter>
					<OnLeave>GameTooltip:Hide();</OnLeave>
				</Scripts>
			</Frame>
			{button("CQ_HeadFold", "-", 20, 18, 0, 0, "CherrysQuests.Tracker.FoldAll();")}
			{button("CQ_HeadOptions", "o", 20, 18, 0, 0, "CherrysQuests.Options.Toggle();")}
{rows}
		</Frames>
	</Frame>
	<Frame name="CQ_Options" parent="UIParent" frameStrata="DIALOG" enableMouse="true" movable="true" hidden="true">
		{size(456, opt_h)}
		<Anchors><Anchor point="CENTER" relativeTo="UIParent" relativePoint="CENTER"><Offset><AbsDimension x="0" y="0" /></Offset></Anchor></Anchors>
		<Backdrop bgFile="Interface/Tooltips/Tooltip-Background" edgeFile="Interface/Tooltips/Tooltip-border">
			<EdgeSize><AbsValue val="16" /></EdgeSize>
			<TileSize><AbsValue val="32" /></TileSize>
			<BackgroundInsets><AbsInset top="4" left="4" bottom="4" right="4" /></BackgroundInsets>
		</Backdrop>
		<Layers>
			<Layer level="ARTWORK">
				<FontString name="CQ_OptionsTitle" inherits="GameFontNormal" justifyH="LEFT" text="Cherry's Quests">{size(380, 20)}<FontHeight><AbsValue val="16" /></FontHeight>{anchor(x=16, y=12)}</FontString>
				<FontString name="CQ_OptionsHint" inherits="GameFontHighlight" justifyH="LEFT" text="">{size(424, 34)}<FontHeight><AbsValue val="11" /></FontHeight>{anchor(x=16, y=44 + OPT_ROWS * 24 + 6)}</FontString>
			</Layer>
		</Layers>
		<Frames>
			{button("CQ_OptionsClose", "X", 28, 24, 416, 10, "CQ_Options:Hide();")}
			{button("CQ_OptionsReset", "Reset position", 130, 26, 16, opt_h - 40, "CherrysQuests.Options.ResetPosition();")}
			{button("CQ_OptionsForget", "Forget NPC picks", 130, 26, 156, opt_h - 40, "CherrysQuests.Options.Forget();")}
			{button("CQ_OptionsDone", "Close", 100, 26, 340, opt_h - 40, "CQ_Options:Hide();")}
{opts}
		</Frames>
		<Scripts>
			<OnMouseDown>this:StartMoving();</OnMouseDown>
			<OnMouseUp>this:StopMovingOrSizing();</OnMouseUp>
		</Scripts>
	</Frame>
</Ui>
"""


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(build().replace("\r\n", "\n").replace("\n", "\r\n").encode("utf-8"))
    print(f"wrote {OUT}")
